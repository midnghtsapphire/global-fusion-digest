import { mkdir, writeFile } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const exec = promisify(execFile);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const directory = resolve(root, 'tests', 'pack-artifacts', new Date().toISOString().replace(/[:.]/g, '-'));
await mkdir(directory, { recursive: true });
const packed = await exec('npm', ['pack', '--json', '--pack-destination', directory], { cwd: root, timeout: 60000 });
const metadata = JSON.parse(packed.stdout)[0];
const installDirectory = resolve(directory, 'installed');
await mkdir(installDirectory);
await writeFile(resolve(installDirectory, 'package.json'), JSON.stringify({ private: true, type: 'module' }) + '\n');
await exec('npm', ['install', '--ignore-scripts', '--no-audit', '--no-fund', resolve(directory, metadata.filename)], { cwd: installDirectory, timeout: 60000 });
const installed = await exec(process.execPath, ['--input-type=module', '-e', 'import {classifyKEV,buildReport,collectIntelligence,runDigest} from "@midnghtsapphire/global-fusion-digest"; import {createApiHandler} from "@midnghtsapphire/global-fusion-digest/api"; console.log(JSON.stringify({exports:[classifyKEV,buildReport,collectIntelligence,runDigest,createApiHandler].every(x=>typeof x === "function")}));'], { cwd: installDirectory });
const cli = await exec(resolve(installDirectory, 'node_modules', '.bin', 'global-fusion'), ['--version'], { cwd: installDirectory });
if (!JSON.parse(installed.stdout).exports || cli.stdout.trim() !== '1.0.0') throw new Error('Installed tarball import/CLI contract failed verification');
const receipt = { directory, tarball: resolve(directory, metadata.filename), metadata, installed_import: JSON.parse(installed.stdout), installed_cli_version: cli.stdout.trim() };
await writeFile(resolve(directory, 'verification.json'), JSON.stringify(receipt, null, 2) + '\n');
console.log(JSON.stringify({ directory, tarball: receipt.tarball, installed_import: receipt.installed_import, installed_cli_version: receipt.installed_cli_version }, null, 2));
